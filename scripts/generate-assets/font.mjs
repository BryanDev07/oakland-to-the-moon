export function glyphWidth(ch) { return ch === ' ' ? 2 : (G[ch] ? G[ch][0].length : 4); }

/** Generate the bitmap font PNG + AngelCode XML (for Phaser BitmapText). */
export function buildFont() {
  const chars = Object.keys(G);
  const cellH = 10, pad = 1;
  let x = 1, y = 1, rowW = 256;
  const entries = [];
  for (const ch of chars) {
    const w = G[ch][0].length;
    if (x + w + pad > rowW) { x = 1; y += cellH + pad; }
    entries.push({ ch, x, y, w });
    x += w + pad;
  }
  const H = y + cellH + 1;
  const b = new Bitmap(rowW, Math.max(16, Math.pow(2, Math.ceil(Math.log2(H)))));
  for (const e of entries) G[e.ch].forEach((row, j) => [...row].forEach((c, i) => { if (c === '#') b.set(e.x + i, e.y + j, '#ffffff'); }));
  save(b, 'ui/font.png');
  const lines = [
    '<?xml version="1.0"?>',
    '<font>',
    '  <info face="TownMono" size="10" bold="0" italic="0" smooth="0"/>',
    `  <common lineHeight="11" base="8" scaleW="${b.w}" scaleH="${b.h}" pages="1"/>`,
    '  <pages><page id="0" file="font.png"/></pages>',
    `  <chars count="${entries.length + 1}">`,
    '    <char id="32" x="0" y="0" width="0" height="0" xoffset="0" yoffset="0" xadvance="3" page="0"/>',
    ...entries.map((e) => `    <char id="${e.ch.codePointAt(0)}" x="${e.x}" y="${e.y}" width="${e.w}" height="${cellH}" xoffset="0" yoffset="1" xadvance="${e.w + 1}" page="0"/>`),
    '  </chars>',
    '</font>',
  ];
  fs.writeFileSync(path.join(OUT, 'ui/font.xml'), lines.join('\n'));
}

/** Render text using glyph data into a bitmap at a given pixel scale with fill function. */
export function drawText(b, text, x, y, scale, fill) {
  let cx = x;
  for (const ch of text) {
    if (ch === ' ') { cx += 3 * scale; continue; }
    const g = G[ch] || G['?'];
    g.forEach((row, j) => [...row].forEach((c, i) => {
      if (c !== '#') return;
      for (let sy = 0; sy < scale; sy++) for (let sx = 0; sx < scale; sx++) {
        const px = cx + i * scale + sx, py = y + j * scale + sy;
        b.set(px, py, fill(px, py, j * scale + sy, 7 * scale));
      }
    }));
    cx += (g[0].length + 1) * scale;
  }
  return cx - x;
}
export function measure(text, scale) {
  let w = 0;
  for (const ch of text) w += ch === ' ' ? 3 * scale : ((G[ch] || G['?'])[0].length + 1) * scale;
  return w - scale;
}

/** Title logo: chunky gradient letters with outline, bevel and drop shadow. */
export function buildLogo() {
  const W = 360, H = 92;
  const b = new Bitmap(W, H);
  const line1 = 'OAKLAND', line2 = 'TO THE MOON';
  const s1 = 5, s2 = 3;
  const w1 = measure(line1, s1), w2 = measure(line2, s2);
  const x1 = Math.floor((W - w1) / 2), x2 = Math.floor((W - w2) / 2);
  const y1 = 6, y2 = 56;
  const goldRamp = [P.gold[7], P.gold[6], P.gold[5], P.gold[4], P.orange[4], P.orange[3], P.red[3]];
  const blueRamp = [P.blue[7], P.blue[6], P.space[8], P.blue[5], P.blue[4]];
  const text = new Bitmap(W, H);
  drawText(text, line1, x1, y1, s1, (px, py, ly, lh) => rampDither(goldRamp, ly / lh, px, py));
  drawText(text, line2, x2, y2, s2, (px, py, ly, lh) => rampDither(blueRamp, ly / lh, px, py));
  // bevel highlight: top-left pixels of each letter area are brightened
  const hl = new Bitmap(W, H);
  for (let y = 0; y < H; y++) for (let x = 0; x < W; x++) {
    if (text.alpha(x, y) && !text.alpha(x, y - 1)) hl.set(x, y, '#fffbe8');
  }
  // drop shadow
  const shadow = new Bitmap(W, H);
  for (let y = 0; y < H; y++) for (let x = 0; x < W; x++) if (text.alpha(x, y)) { shadow.set(x + 3, y + 3, P.sky[1]); }
  b.blit(shadow, 0, 0);
  const outlined = new Bitmap(W, H); outlined.blit(text, 0, 0); outlined.blit(hl, 0, 0);
  outlined.outline(P.ink, true);
  b.blit(outlined, 0, 0);
  // little star sparkles
  const spark = (sx, sy) => { b.set(sx, sy, '#fff'); b.set(sx - 1, sy, P.gold[6]); b.set(sx + 1, sy, P.gold[6]); b.set(sx, sy - 1, P.gold[6]); b.set(sx, sy + 1, P.gold[6]); b.set(sx - 2, sy, mix(P.gold[5], '#000', 0.3)); b.set(sx + 2, sy, mix(P.gold[5], '#000', 0.3)); };
  spark(x1 - 10, y1 + 8); spark(x1 + w1 + 9, y1 + 26); spark(x2 - 8, y2 + 14); spark(x2 + w2 + 8, y2 + 4);
  save(b, 'ui/title_logo.png');
}
