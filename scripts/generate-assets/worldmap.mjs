const MASK = R.map((spans) => { const row = new Array(72).fill(false); for (const [a, b] of spans) for (let c = a; c <= b; c++) row[c] = true; return row; });

export function isLand(lat, lon) {
  let r = Math.floor((90 - lat) / 5); r = Math.max(0, Math.min(35, r));
  let L = ((lon + 180) % 360 + 360) % 360;
  const c = Math.floor(L / 5) % 72;
  return MASK[r][c];
}

/** Bilinear-ish soft land value for smoother coastlines (0..1). */
export function landValue(lat, lon) {
  let s = 0, n = 0;
  for (const dl of [-1.6, 0, 1.6]) for (const dn of [-1.6, 0, 1.6]) { s += isLand(lat + dl, lon + dn) ? 1 : 0; n++; }
  return s / n;
}
